def rows(csv_dir, name):
    with open(os.path.join(csv_dir, name + ".csv"), newline="", encoding="utf-8") as f:
        yield from csv.DictReader(f)


def no_dashes(text):
    """The project writes no em or en dashes: a dash between words becomes a comma, inside a name a hyphen."""
    text = re.sub(r"\s*[\u2014\u2015]\s*", ", ", text)
    text = re.sub(r"\s+\u2013\s+", ", ", text)
    return text.replace("\u2013", "-").replace(" ,", ",").replace(",,", ",")


def clean(text):
    text = text.replace("\u00ad\n", "").replace("\u00ad", "").replace("-\n", "-")
    text = re.sub(r"[\f\n\r\t ]+", " ", text).strip()
    text = no_dashes(text)
    text = text.replace("POKéMON", "Pokémon").replace("POKé BALL", "Poké Ball").replace("POKéBALL", "Poké Ball")
    return text


def lua_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + s + '"'


def lua(value, indent=""):
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return lua_str(value)
    if isinstance(value, list):
        return "{" + ",".join(lua(v, indent) for v in value) + "}"
    if isinstance(value, dict):
        parts = []
        for k, v in value.items():
            if isinstance(k, int):
                key = f"[{k}]"
            elif re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k):
                key = k
            else:
                key = "[" + lua_str(k) + "]"
            parts.append(f"{key}={lua(v, indent)}")
        return "{" + ",".join(parts) + "}"
    raise TypeError(type(value))


def write_lua(path, value, header):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("-- " + header + " Generated by tools/build_data.py from PokeAPI data.\n")
        f.write("return " + lua(value) + "\n")


def to_int(v):
    return int(v) if v not in ("", None) else None


def load(csv_dir):
    d = {}
    d["species"] = {int(r["id"]): r for r in rows(csv_dir, "pokemon_species")}
    d["pokemon"] = {int(r["id"]): r for r in rows(csv_dir, "pokemon")}
    d["forms"] = [r for r in rows(csv_dir, "pokemon_forms")]
    d["types"] = {}
    for r in rows(csv_dir, "pokemon_types"):
        d["types"].setdefault(int(r["pokemon_id"]), []).append((int(r["slot"]), int(r["type_id"])))
    d["form_types"] = {}
    for r in rows(csv_dir, "pokemon_form_types"):
        d["form_types"].setdefault(int(r["pokemon_form_id"]), []).append((int(r["slot"]), int(r["type_id"])))
    d["names"] = {}
    d["genus"] = {}
    for r in rows(csv_dir, "pokemon_species_names"):
        sid = int(r["pokemon_species_id"])
        if r["local_language_id"] in (EN, ES):
            d["names"].setdefault(sid, {})[r["local_language_id"]] = r["name"]
            if r["genus"]:
                d["genus"].setdefault(sid, {})[r["local_language_id"]] = r["genus"]
    d["flavor"] = {}
    for r in rows(csv_dir, "pokemon_species_flavor_text"):
        if r["language_id"] in (EN, ES):
            d["flavor"].setdefault(int(r["species_id"]), {}).setdefault(r["language_id"], {})[int(r["version_id"])] = clean(r["flavor_text"])
    d["form_names"] = {}
    for r in rows(csv_dir, "pokemon_form_names"):
        if r["local_language_id"] in (EN, ES):
            d["form_names"].setdefault(int(r["pokemon_form_id"]), {})[r["local_language_id"]] = (r["form_name"], r["pokemon_name"])
    d["stats"] = {}
    for r in rows(csv_dir, "pokemon_stats"):
        d["stats"].setdefault(int(r["pokemon_id"]), {})[int(r["stat_id"])] = int(r["base_stat"])
    d["abilities"] = {}
    for r in rows(csv_dir, "pokemon_abilities"):
        d["abilities"].setdefault(int(r["pokemon_id"]), []).append((int(r["slot"]), int(r["ability_id"]), int(r["is_hidden"])))
    d["egg_groups"] = {}
    for r in rows(csv_dir, "pokemon_egg_groups"):
        d["egg_groups"].setdefault(int(r["species_id"]), []).append(int(r["egg_group_id"]))
    d["egg_group_ids"] = {int(r["id"]): r["identifier"] for r in rows(csv_dir, "egg_groups")}
    d["growth_ids"] = {int(r["id"]): r["identifier"] for r in rows(csv_dir, "growth_rates")}
    d["evolution"] = [r for r in rows(csv_dir, "pokemon_evolution")]
    d["triggers"] = {int(r["id"]): r["identifier"] for r in rows(csv_dir, "evolution_triggers")}
    d["dex"] = {}
    for r in rows(csv_dir, "pokemon_dex_numbers"):
        d["dex"].setdefault(int(r["pokedex_id"]), []).append((int(r["pokedex_number"]), int(r["species_id"])))
    d["versions"] = {int(r["id"]): int(r["version_group_id"]) for r in rows(csv_dir, "versions")}
    return d


def latest(texts):
    best = None
    for v in VERSION_ORDER:
        if v in texts:
            best = texts[v]
    if best is None and texts:
        best = texts[max(texts)]
    return best


def ability_texts(csv_dir):
    names, texts = {}, {}
    for r in rows(csv_dir, "ability_names"):
        if r["local_language_id"] in (EN, ES):
            names.setdefault(int(r["ability_id"]), {})[r["local_language_id"]] = r["name"]
    # A text that two abilities share is a data error (it happened with
    # Queenly Majesty and Gulp Missile), so it is left out and an older text is used.
    all_rows = [r for r in rows(csv_dir, "ability_flavor_text") if r["language_id"] in (EN, ES)]
    owners = {}
    for r in all_rows:
        owners.setdefault((r["language_id"], clean(r["flavor_text"])), set()).add(r["ability_id"])
    order = {}
    for r in all_rows:
        aid, vg = int(r["ability_id"]), int(r["version_group_id"])
        text = clean(r["flavor_text"])
        if len(owners[(r["language_id"], text)]) > 1:
            continue
        key = (aid, r["language_id"])
        if key not in order or vg > order[key]:
            order[key] = vg
            texts.setdefault(aid, {})[r["language_id"]] = text
    for r in rows(csv_dir, "ability_prose"):
        if r["local_language_id"] == EN and r["short_effect"]:
            aid = int(r["ability_id"])
            texts.setdefault(aid, {}).setdefault(EN, clean(r["short_effect"]))
    return names, texts


def write_sources(csv_dir, out):
    d = load(csv_dir)
    species = {}
    for sid in sorted(d["species"]):
        en_flavor = latest(d["flavor"].get(sid, {}).get(EN, {}))
        es_flavor = latest(d["flavor"].get(sid, {}).get(ES, {}))
        species[sid] = {
            "name": d["names"][sid][EN],
            "genus_en": d["genus"].get(sid, {}).get(EN, ""),
            "genus_es": d["genus"].get(sid, {}).get(ES, ""),
            "flavor_en": en_flavor or "",
            "flavor_es": es_flavor or "",
        }
    names, texts = ability_texts(csv_dir)
    abilities = {aid: {"name": names[aid].get(EN, ""), "text_en": t.get(EN, ""), "text_es": t.get(ES, "")}
                 for aid, t in sorted(texts.items()) if aid < 10000 and aid in names}
    forms = {}
    for fid, langs in d["form_names"].items():
        en = langs.get(EN)
        if en and en[0]:
            forms.setdefault(en[0], langs.get(ES, ("", ""))[0])
    os.makedirs(out, exist_ok=True)
    for name, value in (("species", species), ("abilities", abilities), ("forms", dict(sorted(forms.items())))):
        with open(os.path.join(out, name + ".json"), "w", encoding="utf-8") as f:
            json.dump(value, f, ensure_ascii=False, indent=1)
    print(f"sources: {len(species)} species, {len(abilities)} abilities, {len(forms)} form names")


def read_json(path, default):
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    return default


def form_sprite(form, pokemon):
    if pokemon["is_default"] == "0":
        return str(pokemon["id"])
    if form["is_default"] == "0" and form["form_identifier"]:
        return pokemon["species_id"] + "-" + form["form_identifier"]
    return pokemon["species_id"]


def evolution_condition(r, d):
    c = {"t": d["triggers"][int(r["evolution_trigger_id"])]}
    fields = {
        "trigger_item_id": "item", "minimum_level": "lv", "gender_id": "gender", "location_id": "loc",
        "held_item_id": "held", "known_move_id": "move", "known_move_type_id": "move_type", "minimum_happiness": "happy",
        "minimum_beauty": "beauty", "minimum_affection": "affection", "relative_physical_stats": "phys",
        "party_species_id": "party", "party_type_id": "party_type", "trade_species_id": "trade_with",
        "used_move_id": "used_move", "minimum_move_count": "move_count", "minimum_steps": "steps",
        "minimum_damage_taken": "damage", "region_id": "region",
    }
    for src, dst in fields.items():
        v = to_int(r.get(src))
        if v is not None:
            c[dst] = v
    if r.get("time_of_day"):
        c["time"] = r["time_of_day"]
    for flag, dst in (("needs_overworld_rain", "rain"), ("turn_upside_down", "upside_down"), ("needs_multiplayer", "multiplayer")):
        if r.get(flag) == "1":
            c[dst] = True
    return c


