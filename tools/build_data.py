def game_forms(d, csv_dir, forms_by_species, pkhex_core):
    """Which forms each game has, for the species of its Pokédex: { game: { species: [form keys] } }.
    From Sword and Shield on, PKHeX's tables say it; before, a form counts from the game it came in."""
    order = {int(r["id"]): int(r["order"]) for r in rows(csv_dir, "version_groups")}
    introduced = {}
    for f in d["forms"]:
        p = d["pokemon"][int(f["pokemon_id"])]
        key = f["form_identifier"] or f["identifier"]
        introduced[(int(p["species_id"]), key)] = order.get(to_int(f["introduced_in_version_group_id"]) or 0, 0)
    # PKHeX numbers the forms of a species like PokeAPI's form order, Gigantamax aside.
    by_number = {}
    for f in d["forms"]:
        p = d["pokemon"][int(f["pokemon_id"])]
        if (f["form_identifier"] or "").endswith("gmax"):
            continue
        by_number.setdefault(int(p["species_id"]), []).append((int(f["form_order"]), f["form_identifier"] or f["identifier"]))
    for sid in by_number:
        by_number[sid].sort()
    tables = {}
    if pkhex_core:
        import pkhex
        for t in ("swsh", "bdsp", "la", "sv", "za"):
            keys = set()
            for sid, number in pkhex.present_forms(pkhex_core, t):
                forms = by_number.get(sid, [])
                if number < len(forms):
                    keys.add((sid, forms[number][1]))
            tables[t] = keys
    out = {}
    for game, vg, dexes, table in GAMES:
        species = set()
        for dex in dexes:
            species.update(s for _, s in d["dex"].get(dex, []))
        game_out = {}
        for sid in sorted(species):
            keys = []
            for f in forms_by_species.get(sid, []):
                if f["battle"]:
                    continue
                if table and table in tables:
                    ok = (sid, f["key"]) in tables[table]
                else:
                    ok = 0 < introduced.get((sid, f["key"]), 999) <= order.get(vg, 0)
                if ok:
                    keys.append(f["key"])
            if keys:
                game_out[sid] = keys
        out[game] = game_out
    return out


def build(csv_dir, out, pkhex_core=None):
    d = load(csv_dir)
    tr_species = read_json(os.path.join(TRANSLATIONS, "species.json"), {})
    tr_abilities = read_json(os.path.join(TRANSLATIONS, "abilities.json"), {})
    tr_forms = read_json(os.path.join(TRANSLATIONS, "forms.json"), {})
    # Spanish texts PokeAPI does not have yet, translated from English: everything translated to Portuguese
    # also exists in Spanish.
    es_fill = read_json(os.path.join(HERE, "translations", "es", "species.json"), {})
    es_abilities = read_json(os.path.join(HERE, "translations", "es", "abilities.json"), {})
    es_forms = read_json(os.path.join(HERE, "translations", "es", "forms.json"), {})
    manifest = read_json(MANIFEST, None)
    if manifest is None:
        sys.exit("tools/sources/sprites_manifest.json not found: run fetch_sprite_manifest.py first.")

    # Default pokemon of each species.
    default_pokemon = {}
    for pid, p in d["pokemon"].items():
        if p["is_default"] == "1":
            default_pokemon[int(p["species_id"])] = p

    def types_of_pokemon(pid):
        return [t for _, t in sorted(d["types"].get(pid, []))]

    # Forms: every form except the default one of the default pokemon.
    forms_by_species = {}
    for f in sorted(d["forms"], key=lambda r: (int(d["pokemon"][int(r["pokemon_id"])]["species_id"]), int(r["order"]))):
        p = d["pokemon"][int(f["pokemon_id"])]
        sid = int(p["species_id"])
        if p["is_default"] == "1" and f["is_default"] == "1":
            continue
        fid = int(f["id"])
        langs = d["form_names"].get(fid, {})
        en_form, en_full = langs.get(EN, ("", ""))
        es_form, es_full = langs.get(ES, ("", ""))
        species_en = d["names"][sid][EN]
        species_es = d["names"][sid].get(ES, species_en)
        label_en = en_full or (f"{species_en} ({en_form})" if en_form else f["identifier"])
        if not es_full and not es_form and en_form and es_forms.get(en_form):
            es_form = es_forms[en_form]
        label_es = es_full or ((es_form if species_es in es_form else f"{species_es} ({es_form})") if es_form else label_en)
        label_pt = tr_forms.get(en_form) if en_form else None
        # A form name that does not say which Pokémon it is ("Forma de Hisui", "B") gets the species in front.
        if label_pt and species_en not in label_pt:
            label_pt = f"{species_en} ({label_pt})"
        types = [t for _, t in sorted(d["form_types"].get(fid, []))] or types_of_pokemon(int(p["id"]))
        forms_by_species.setdefault(sid, []).append({
            "key": f["form_identifier"] or f["identifier"],
            "sprite": form_sprite(f, p),
            "battle": 1 if f["is_battle_only"] == "1" else 0,
            "mega": 1 if f["is_mega"] == "1" else 0,
            "types": types,
            "en": label_en, "es": label_es, "pt": label_pt or "", "form_en": en_form,
            "pokemon": int(p["id"]),
        })

    species_index = {}
    names_es = {}
    for sid, s in sorted(d["species"].items()):
        p = default_pokemon[sid]
        t = types_of_pokemon(int(p["id"]))
        flags = (1 if s["is_legendary"] == "1" else 0) | (2 if s["is_mythical"] == "1" else 0) | (4 if s["is_baby"] == "1" else 0) | (8 if s["has_gender_differences"] == "1" else 0)
        species_index[sid] = [d["names"][sid][EN], int(s["generation_id"]), t[0], t[1] if len(t) > 1 else 0, flags, int(s["gender_rate"]), int(s["evolution_chain_id"])]
        es = d["names"][sid].get(ES)
        if es and es != d["names"][sid][EN]:
            names_es[sid] = es

    forms_index = {}
    for sid, forms in forms_by_species.items():
        forms_index[sid] = [[f["key"], f["sprite"], f["battle"], f["types"][0], f["types"][1] if len(f["types"]) > 1 else 0, f["en"], f["es"], f["pt"] or f["en"]] for f in forms]

    dexes = {}
    for dex_id, entries in d["dex"].items():
        entries.sort()
        dexes[dex_id] = [[n, s] for n, s in entries]

    # Sprite sets: which ids each folder has, and the average size of a file.
    folders = {}
    for name, info in manifest["folders"].items():
        files = info["files"]
        avg = round(sum(files.values()) / len(files)) if files else 0
        folders[name] = {"ext": info["ext"], "avg": avg, "ids": sorted(files.keys(), key=lambda k: (len(k), k))}
    write_lua(os.path.join(out, "sprites.lua"), {"commit": manifest["commit"], "root": manifest["root"], "folders": folders},
              "Sprite folders of PokeAPI/sprites at a fixed commit.")
    per_game = game_forms(d, csv_dir, forms_by_species, pkhex_core)
    write_lua(os.path.join(out, "index.lua"), {"species": species_index, "names_es": names_es, "forms": forms_index, "dex": dexes, "game_forms": per_game},
              "Species, forms, Pokédex lists and the forms of each game.")

    # Detail of each species.
    chains = {}
    for sid, s in d["species"].items():
        chains.setdefault(int(s["evolution_chain_id"]), []).append(sid)
    evo_by_species = {}
    for r in d["evolution"]:
        evo_by_species.setdefault(int(r["evolved_species_id"]), []).append(r)

    names, ability_tx = ability_texts(csv_dir)
    level_moves = {}
    used_moves = set()
    for r in rows(csv_dir, "pokemon_moves"):
        if r["pokemon_move_method_id"] != "1":
            continue
        pid = int(r["pokemon_id"])
        level_moves.setdefault(pid, {}).setdefault(int(r["version_group_id"]), []).append((int(r["level"] or 0), int(r["order"] or 0), int(r["move_id"])))
    encounters = {}
    slot_method = {int(r["id"]): int(r["encounter_method_id"]) for r in rows(csv_dir, "encounter_slots")}
    slot_rarity = {int(r["id"]): int(r["rarity"] or 0) for r in rows(csv_dir, "encounter_slots")}
    used_areas = set()
    # The chance of a Pokémon in a place: the sum of its slots under the same conditions (time, season,
    # radio...), and the highest of those sums, so morning, day and night are not added together.
    conditions = {}
    for r in rows(csv_dir, "encounter_condition_value_map"):
        conditions.setdefault(r["encounter_id"], []).append(r["encounter_condition_value_id"])
    sums = {}
    for r in rows(csv_dir, "encounters"):
        pid = int(r["pokemon_id"])
        version = int(r["version_id"])
        slot = int(r["encounter_slot_id"])
        key = (int(r["location_area_id"]), slot_method.get(slot, 0))
        e = encounters.setdefault(pid, {}).setdefault(version, {}).setdefault(key, [999, 0, 0])
        e[0] = min(e[0], int(r["min_level"]))
        e[1] = max(e[1], int(r["max_level"]))
        cond = ",".join(sorted(conditions.get(r["id"], [])))
        per = sums.setdefault((pid, version, key), {})
        per[cond] = per.get(cond, 0) + slot_rarity.get(slot, 0)
        e[2] = min(100, max(per.values()))
        used_areas.add(key[0])
    used_items, used_locations = set(), set()
    pk_enc = None
    if pkhex_core:
        import pkhex
        pk_enc = pkhex.encounters(pkhex_core)
    # Chances of Brilliant Diamond and Shining Pearl, from Serebii (tools/serebii.py), matched by place name.
    serebii = {}

    def place_key(name):
        name = name.lower().replace("é", "e").replace("’", "'").replace("mount ", "mt. ")
        return re.sub(r"[^a-z0-9]", "", name).replace("ruinmaniaccave", "maniactunnel")

    for place, data in read_json(os.path.join(HERE, "sources", "serebii_bdsp.json"), {}).items():
        serebii[place_key(place)] = data

    def serebii_chance(place, version, method, sid):
        data = serebii.get(place_key(place))
        if not data:
            return 0
        return data.get(str(version), {}).get(str(method), {}).get(str(sid), 0)

    count = 0
    for sid, s in sorted(d["species"].items()):
        p = default_pokemon[sid]
        pid = int(p["id"])
        stats = d["stats"].get(pid, {})
        flavor = d["flavor"].get(sid, {})
        tr = tr_species.get(str(sid), {})
        evo = []
        for member in sorted(chains[int(s["evolution_chain_id"])], key=lambda m: int(d["species"][m]["order"])):
            node = {"s": member}
            frm = to_int(d["species"][member]["evolves_from_species_id"])
            if frm:
                node["from"] = frm
                conds = []
                seen = set()
                for r in evo_by_species.get(member, []):
                    c = evolution_condition(r, d)
                    k = json.dumps(c, sort_keys=True)
                    if k not in seen:
                        seen.add(k)
                        conds.append(c)
                        for field in ("item", "held"):
                            if field in c:
                                used_items.add(c[field])
                        for field in ("move", "used_move"):
                            if field in c:
                                used_moves.add(c[field])
                        if "loc" in c:
                            used_locations.add(c["loc"])
                node["c"] = conds
            evo.append(node)
        moves = {}
        for vg, lst in level_moves.get(pid, {}).items():
            lst.sort()
            flat = []
            for lv, _, mid in lst:
                flat += [lv, mid]
                used_moves.add(mid)
            moves[vg] = flat
        enc = {}
        for version, areas in encounters.get(pid, {}).items():
            flat = []
            for (area, method), (lo, hi, chance) in sorted(areas.items()):
                flat += [area, method, lo, hi, chance]
            enc[version] = flat
        if pk_enc:
            for version, areas in pk_enc.enc.get(sid, {}).items():
                flat = enc.setdefault(version, [])
                for (area, method), (lo, hi) in sorted(areas.items()):
                    chance = serebii_chance(pk_enc.areas[area][0], version, method, sid)
                    flat += [area, method, lo, hi, chance]
        detail = {
            "h": int(p["height"]), "w": int(p["weight"]),
            "cr": int(s["capture_rate"]), "hc": to_int(s["hatch_counter"]), "bh": to_int(s["base_happiness"]),
            "gr": d["growth_ids"].get(to_int(s["growth_rate_id"]), ""),
            "eg": [d["egg_group_ids"][g] for g in d["egg_groups"].get(sid, [])],
            "st": [stats.get(i, 0) for i in range(1, 7)],
            "ab": [[a, h] for _, a, h in sorted(d["abilities"].get(pid, []))],
            "genus": {"en": d["genus"].get(sid, {}).get(EN, ""), "es": d["genus"].get(sid, {}).get(ES, "") or es_fill.get(str(sid), {}).get("genus", ""), "pt": tr.get("genus", "")},
            "flavor": {"en": flavor.get(EN, {}), "es": flavor.get(ES, {}) or ({0: es_fill[str(sid)]["flavor"]} if es_fill.get(str(sid), {}).get("flavor") else {}), "pt": tr.get("flavor", "")},
            "evo": evo,
            "moves": moves,
            "enc": enc,
        }
        forms = forms_by_species.get(sid)
        if forms:
            detail["forms"] = [{"key": f["key"], "pokemon": f["pokemon"]} for f in forms]
        write_lua(os.path.join(out, "species", f"{sid}.lua"), detail, f"{d['names'][sid][EN]}.")
        count += 1

    move_names = {}
    for r in rows(csv_dir, "move_names"):
        mid = int(r["move_id"])
        if mid in used_moves and r["local_language_id"] in (EN, ES):
            move_names.setdefault(mid, {})[r["local_language_id"]] = r["name"]
    move_types = {int(r["id"]): int(r["type_id"]) for r in rows(csv_dir, "moves")}
    moves_out = {mid: [n.get(EN, ""), n.get(ES, n.get(EN, "")), move_types.get(mid, 0)] for mid, n in sorted(move_names.items())}
    write_lua(os.path.join(out, "moves.lua"), moves_out, "Move names (English, Spanish) and type.")

    abilities_out = {}
    for aid, n in sorted(names.items()):
        if aid >= 10000:
            continue
        t = ability_tx.get(aid, {})
        es_text = t.get(ES) if t.get(ES) and t.get(ES) != t.get(EN) else (es_abilities.get(str(aid)) or t.get(EN, ""))
        abilities_out[aid] = [n.get(EN, ""), n.get(ES, n.get(EN, "")), t.get(EN, ""), es_text, tr_abilities.get(str(aid), "")]
    write_lua(os.path.join(out, "abilities.lua"), abilities_out, "Abilities: names and texts (English, Spanish, Portuguese).")

    items_out = {}
    for r in rows(csv_dir, "item_names"):
        iid = int(r["item_id"])
        if iid in used_items and r["local_language_id"] in (EN, ES):
            items_out.setdefault(iid, {})[r["local_language_id"]] = r["name"]
    write_lua(os.path.join(out, "items.lua"), {i: [n.get(EN, ""), n.get(ES, n.get(EN, ""))] for i, n in sorted(items_out.items())},
              "Item names used in evolutions (English, Spanish).")

    loc_names = {}
    for r in rows(csv_dir, "location_names"):
        if r["local_language_id"] in (EN, ES):
            loc_names.setdefault(int(r["location_id"]), {})[r["local_language_id"]] = r["name"]
    area_loc = {int(r["id"]): int(r["location_id"]) for r in rows(csv_dir, "location_areas")}
    area_names = {}
    for r in rows(csv_dir, "location_area_prose"):
        if r["local_language_id"] in (EN, ES):
            area_names.setdefault(int(r["location_area_id"]), {})[r["local_language_id"]] = r["name"]
    # Spanish place names: PokeAPI has few, so the official ones come from PKHeX's lists, matched by the English name.
    es_places = {}
    if pkhex_core:
        import pkhex
        es_places = pkhex.place_dictionary(pkhex_core)

    manual_places = read_json(os.path.join(HERE, "translations", "es", "places.json"), {})

    def to_es(name):
        if not name:
            return name
        if name in manual_places:
            return manual_places[name]
        key = name.lower().replace("\u2019", "'").replace("\u00e9", "e")
        found = es_places.get(key) or es_places.get(key.replace("mt.", "mt"))
        if not found and key.startswith("sea route "):
            found = es_places.get(key[4:])
        return found or name

    def suffix_es(suffix):
        words = {"south": "sur", "north": "norte", "east": "este", "west": "oeste", "towards": "hacia", "and": "y",
                 "outside": "exterior", "inside": "interior", "entrance": "entrada", "area": "zona", "room": "sala",
                 "floor": "piso", "back": "fondo", "front": "frente", "exterior": "exterior", "interior": "interior"}
        parts = []
        suffix = re.sub(r"\bMax Den\b", "Guarida Dinamax", suffix)
        for chunk in suffix.split(", "):
            m = re.match(r"^(\w+) (.+)$", chunk)
            if m and m.group(1).lower() in words and to_es(m.group(2)) != m.group(2):
                parts.append(words[m.group(1).lower()] + " " + to_es(m.group(2)))
            elif to_es(chunk) != chunk:
                parts.append(to_es(chunk))
            else:
                parts.append(" ".join(words.get(w.lower(), w) for w in chunk.split(" ")))
        return ", ".join(parts)

    areas_out = {}
    for area in sorted(used_areas):
        loc = loc_names.get(area_loc.get(area), {})
        own = area_names.get(area, {})
        loc_en = loc.get(EN) or own.get(EN) or ""
        # PokeAPI's own area names are old ("Road 201"): the official location name plus the part that tells the
        # area apart ("1F", "south, towards Jubilife City").
        prose = own.get(EN) or ""
        suffix = ""
        m = re.match(r"^.*?\((.*)\)$", prose)
        if m:
            suffix = m.group(1)
        elif prose.lower().startswith(loc_en.lower()) and len(prose) > len(loc_en):
            suffix = prose[len(loc_en):].strip(" -")
        en = loc_en + (f" ({suffix})" if suffix else "")
        loc_es = loc.get(ES) or to_es(loc_en)
        es = own.get(ES) or (loc_es + (f" ({suffix_es(suffix)})" if suffix else ""))
        areas_out[area] = [no_dashes(en).replace(", ", " - ") if "\u2013" in en or "\u2014" in en else en, no_dashes(es)]
    if pk_enc:
        for area, names in pk_enc.areas.items():
            areas_out[area] = [no_dashes(names[0]), no_dashes(names[1])]
    locations_out = {loc: [no_dashes(loc_names.get(loc, {}).get(EN, "")), no_dashes(loc_names.get(loc, {}).get(ES) or to_es(loc_names.get(loc, {}).get(EN, "")))] for loc in sorted(used_locations)}
    write_lua(os.path.join(out, "places.lua"), {"areas": areas_out, "locations": locations_out}, "Place names (English, Spanish).")
    print(f"data: {count} species, {len(moves_out)} moves, {len(abilities_out)} abilities, {len(areas_out)} areas")
    missing = [sid for sid in d["species"] if not tr_species.get(str(sid), {}).get("flavor")]
    if missing:
        print(f"warning: {len(missing)} species without a Portuguese text")


