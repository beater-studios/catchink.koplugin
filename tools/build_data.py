"""Builds the CatchInk data files from the PokeAPI CSVs.

Usage:
  build_data.py <pokeapi csv dir> --out data [--pkhex <PKHeX.Core dir>]
                                                        writes the Lua data the plugin reads; with PKHeX, also the
                                                        encounters of BDSP, Legends: Arceus, SV and Z-A
  build_data.py <pokeapi csv dir> --sources <dir>       writes the English and Spanish texts to translate

The Portuguese texts come from tools/translations/pt (species.json, abilities.json, forms.json).
The sprite list comes from tools/sources/sprites_manifest.json (fetch_sprite_manifest.py).
"""
